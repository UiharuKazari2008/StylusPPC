"""Builds HTCSensorService.dll, PocketStylus' SEN0: G-sensor driver for HTC apps (guest/Sensor/htcsensor.c).

NDK clang compiles the C file freestanding for ARMv4T; make-mapilib.py's PE builder links it into a
Windows CE ARM DLL (exports SEN_* and DllMain by name, coredll imports, base relocations). The DLL goes
as base64 into guest/Helper/SensorDll.cs, from which the helper installs it as
\\Windows\\HTCSensorService.dll (--out also writes the DLL itself, for tests).

    python tools/make-htcsensor.py [--out path]
"""
import base64, importlib.util, os, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load(name, file):
    spec = importlib.util.spec_from_file_location(name, os.path.join(ROOT, 'tools', file))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


mm = load('make_mapilib', 'make-mapilib.py')
ma = mm.ma
SRC = os.path.join(ROOT, 'guest', 'Sensor', 'htcsensor.c')
CS = os.path.join(ROOT, 'guest', 'Helper', 'SensorDll.cs')


def build(src, dllname, prefixes, cs, cls, out=None, ordinal_base=1):
    """Compile one freestanding C file into a CE ARM DLL; write it as base64 class `cls` into `cs`."""
    clang, lld = ma.tools()
    with tempfile.TemporaryDirectory() as d:
        obj, lds, elf = (os.path.join(d, 'dll' + e) for e in ('.o', '.lds', '.elf'))
        cflags = [f for f in mm.CFLAGS if f != '-Wno-everything'] + ['-Wall', '-Werror']
        subprocess.check_call([clang] + cflags + ['-c', src, '-o', obj])
        open(lds, 'w').write(mm.LINKER_SCRIPT)
        subprocess.check_call([lld, '-T', lds, '-e', 'DllMain', '--no-undefined', '--emit-relocs', '-o', elf, obj])
        b = open(elf, 'rb').read()
    entry, sections, symbols = ma.parse_elf(b)
    dll, exports, dlls, nrel = mm.build_pe(entry, sections, symbols, mm.abs32_relocs(b, sections),
                                           dllname=dllname, prefixes=prefixes, ordinal_base=ordinal_base)
    if out:
        open(out, 'wb').write(dll)
    b64 = base64.b64encode(dll).decode()
    lines = ['        "%s" +' % b64[i:i + 100] for i in range(0, len(b64), 100)]
    lines[-1] = lines[-1][:-2] + ';'
    nl = chr(10)
    with open(cs, 'w', newline=nl) as f:
        f.write('// Generated by tools/%s from %s: do not edit.%s' % (os.path.basename(sys.argv[0]), os.path.relpath(src, ROOT).replace(os.sep, '/'), nl))
        f.write(nl.join(['static class %s' % cls, '{', '    // %s, %d bytes' % (dllname, len(dll)), '    public const string Base64 =']) + nl)
        f.write(nl.join(lines) + nl + '}' + nl)
    ords = ' '.join('%s@%d' % (e, ordinal_base + i) for i, e in enumerate(exports))
    print('%s: %d bytes, exports %s, imports from %s, %d relocations -> %s'
          % (dllname, len(dll), ords, ', '.join(dlls), nrel, out or cs))


def main():
    out = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else None
    build(SRC, 'HTCSensorService.dll', ('SEN_',), CS, 'SensorDll', out)


if __name__ == '__main__':
    main()
